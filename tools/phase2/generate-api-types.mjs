// AQ-07: the frontend's API types come from the public OpenAPI contract
// (backend/openapi.json, the gateway surface for Core and Clinic), not from hand
// copies. `node tools/phase2/generate-api-types.mjs` rewrites
// frontend/src/types/generated/api.ts; `--check` only compares and exits 1 when
// the committed file is stale (run by arch:check). No dependency: the subset of
// OpenAPI 3.0 this repo uses (object/array/enum/nullable/$ref/oneOf/anyOf/allOf,
// additionalProperties) maps directly to TypeScript.
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {pathToFileURL} from 'node:url';

const root=resolve(import.meta.dirname,'../..');
export const SPEC=resolve(root,'backend/openapi.json');
export const OUTPUT=resolve(root,'frontend/src/types/generated/api.ts');

const key=name=>/^[A-Za-z_$][\w$]*$/.test(name)?name:JSON.stringify(name);
const literal=value=>typeof value==='string'?JSON.stringify(value):String(value);
const indent=(text,pad)=>text.replaceAll('\n','\n'+pad);

export function typeOf(schema,pad=''){
  if(!schema||typeof schema!=='object')return 'unknown';
  let type;
  if(schema.$ref){
    const m=/^#\/components\/schemas\/(.+)$/.exec(schema.$ref);
    if(!m)throw new Error('UNSUPPORTED_REF '+schema.$ref);
    type=`ApiSchemas[${JSON.stringify(m[1])}]`;
  }else if(schema.enum)type=schema.enum.map(literal).join(' | ');
  else if(schema.oneOf||schema.anyOf)type=(schema.oneOf??schema.anyOf).map(s=>wrap(typeOf(s,pad))).join(' | ');
  else if(schema.allOf)type=schema.allOf.map(s=>wrap(typeOf(s,pad))).join(' & ');
  else if(schema.type==='array')type=`${wrap(typeOf(schema.items,pad))}[]`;
  else if(schema.type==='string')type='string';
  else if(schema.type==='integer'||schema.type==='number')type='number';
  else if(schema.type==='boolean')type='boolean';
  else if(schema.type==='object'||schema.properties||schema.additionalProperties)type=objectOf(schema,pad);
  else type='unknown';
  return schema.nullable&&type!=='unknown'?`${wrap(type)} | null`:type;
}
const wrap=type=>/[|&]/.test(type)&&!/^\{[\s\S]*\}$/.test(type)?`(${type})`:type;

function objectOf(schema,pad){
  const props=Object.entries(schema.properties??{}),required=new Set(schema.required??[]);
  const extra=schema.additionalProperties;
  if(!props.length)return extra&&typeof extra==='object'?`Record<string, ${typeOf(extra,pad)}>`:'Record<string, unknown>';
  const inner=pad+'  ';
  const lines=props.map(([name,value])=>{
    const doc=value.description?`${inner}/** ${value.description.replaceAll('*/','*\\/').replace(/\s+/g,' ')} */\n`:'';
    return `${doc}${inner}${key(name)}${required.has(name)?'':'?'}: ${typeOf(value,inner)};`;
  });
  return `{\n${lines.join('\n')}\n${pad}}`;
}

export function generate(spec){
  const schemas=Object.entries(spec.components?.schemas??{});
  const body=schemas.map(([name,schema])=>`  ${key(name)}: ${indent(typeOf(schema,'  '),'')};`).join('\n');
  return `// Generated by tools/phase2/generate-api-types.mjs from backend/openapi.json (OpenAPI ${spec.openapi}).
// Do not edit: change the contract, then run \`node tools/phase2/generate-api-types.mjs\`.
// arch:check fails when this file is stale (AQ-07).
/* eslint-disable */
export interface ApiSchemas {
${body}
}
`;
}

if(import.meta.url===pathToFileURL(process.argv[1]??'').href){
  const next=generate(JSON.parse(readFileSync(SPEC,'utf8')));
  if(process.argv.includes('--check')){
    let current='';try{current=readFileSync(OUTPUT,'utf8');}catch{}
    if(current.replaceAll('\r\n','\n')!==next){process.stderr.write('STALE: frontend/src/types/generated/api.ts differs from backend/openapi.json; run node tools/phase2/generate-api-types.mjs\n');process.exitCode=1;}
    else process.stdout.write(`API types PASS: ${Object.keys(JSON.parse(readFileSync(SPEC,'utf8')).components.schemas).length} schemas match backend/openapi.json\n`);
  }else{mkdirSync(dirname(OUTPUT),{recursive:true});writeFileSync(OUTPUT,next);process.stdout.write('wrote '+OUTPUT+'\n');}
}
